export interface DropItem {
  id: string;
  name: string;
  iconUrl: string;
  members: boolean;
  /** Base coin value when sold, per unit (unnoted). */
  value: number;
  /** Whether this item can be sold for coins at all (false for pets, clue scrolls, and other untradeables). */
  tradeable: boolean;
  /** Cache-derived: whether this item stacks in a single inventory slot when unnoted (noted items always stack regardless). */
  stackable: boolean;
}

export interface DropEntry {
  itemId: string;
  minQuantity: number;
  maxQuantity: number;
  numerator: number;
  denominator: number;
  noted?: boolean;
}

export interface LootTable {
  always: DropEntry[];
  mainTable: DropEntry[];
  /** Number of independent rolls against mainTable per opening/kill (defaults to 1). */
  mainRolls?: number;
  tertiary: DropEntry[];
}

export interface Npc extends LootTable {
  id: string;
  name: string;
  combatLevel: number;
  iconUrl: string;
  examine: string;
  category: 'low' | 'mid' | 'boss';
  /** Coins required to unlock this monster (0 = unlocked from the start). */
  unlockCost: number;
}

/** An inventory item that can be opened/rolled for its own loot table (clue caskets, chest keys). */
export interface ContainerDef extends LootTable {
  itemId: string;
  name: string;
}

