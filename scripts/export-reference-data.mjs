#!/usr/bin/env node
/**
 * Exports npc/item reference data used to seed Postgres validation tables
 * (see supabase/migrations). Transpiles src/data/npcData.ts with esbuild for
 * its merge functions and hand-authored data, reads the bulk-generated
 * public/data/*.json directly, and merges them the same way the browser
 * does — so this is always in sync with the real app data rather than a
 * second hand-maintained copy.
 *
 * Output: supabase/reference-data.json
 */
import { build } from "esbuild";
import { writeFileSync, readFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

function maxCoinsPerRoll(entries) {
  const coinEntries = entries.filter((e) => e.itemId === "coins");
  return coinEntries.reduce((sum, e) => sum + e.maxQuantity, 0);
}

/** The exact loot-table shape the server's public._roll_loot() reads — the
 * same fields src/utils/dropLogic.ts's rollDrop() reads, nothing else. */
function lootOf(table) {
  return {
    always: table.always ?? [],
    mainTable: table.mainTable ?? [],
    mainRolls: table.mainRolls ?? 1,
    tertiary: table.tertiary ?? [],
    tertiaryGroups: table.tertiaryGroups ?? [],
  };
}

async function transpile(entry, name) {
  const outfile = path.join(mkdtempSync(path.join(tmpdir(), `${name}-`)), `${name}.cjs`);
  await build({ entryPoints: [path.join(ROOT, entry)], bundle: true, platform: "node", format: "cjs", outfile });
  return import(`file://${outfile}`);
}

async function main() {
  const { mergeNpcs, mergeItems, containers } = await transpile("src/data/npcData.ts", "npcData");
  const { PET_ITEM_IDS } = await transpile("src/data/pets.ts", "pets");
  const generatedMonsters = JSON.parse(readFileSync(path.join(ROOT, "public/data/monsters.json"), "utf8"));
  const generatedItems = JSON.parse(readFileSync(path.join(ROOT, "public/data/items.json"), "utf8"));
  const npcs = mergeNpcs(generatedMonsters);
  const items = mergeItems(generatedItems);

  const npcReference = npcs.map((npc) => {
    // Generous ceiling: guaranteed coins + best possible single main-table coin
    // hit + every tertiary coin entry landing at once, times the roll count,
    // doubled for safety margin. Not exact game math — just a sanity bound.
    const alwaysCoins = maxCoinsPerRoll(npc.always);
    const mainCoins = Math.max(0, ...npc.mainTable.filter((e) => e.itemId === "coins").map((e) => e.maxQuantity), 0);
    const tertiaryCoins = maxCoinsPerRoll(npc.tertiary);
    const rolls = npc.mainRolls ?? 1;
    const ceiling = (alwaysCoins + mainCoins * rolls + tertiaryCoins) * 2 + 1000;
    return { id: npc.id, name: npc.name, unlockCost: npc.unlockCost, maxGpPerKill: ceiling, loot: lootOf(npc) };
  });

  const itemReference = Object.fromEntries(
    Object.values(items).map((it) => [it.id, { name: it.name, value: it.value, tradeable: it.tradeable, isPet: PET_ITEM_IDS.has(it.id) }]),
  );

  const containerReference = Object.fromEntries(
    Object.values(containers).map((c) => {
      const ceiling = (maxCoinsPerRoll(c.always) + maxCoinsPerRoll(c.mainTable) * (c.mainRolls ?? 1) + maxCoinsPerRoll(c.tertiary)) * 2 + 1000;
      return [c.itemId, { name: c.name, maxGpPerOpen: ceiling, loot: lootOf(c) }];
    }),
  );

  const out = { npcs: npcReference, items: itemReference, containers: containerReference };
  writeFileSync(path.join(ROOT, "supabase/reference-data.json"), JSON.stringify(out, null, 2));

  // Supabase's migration tracker keys off filename, so re-running this
  // against an already-migrated database requires a NEW file each time —
  // overwriting 0003_seed_reference.sql's content wouldn't get re-applied.
  const timestamp = new Date().toISOString().replace(/[-:TZ]|\.\d+/g, "").slice(0, 14);
  const migrationPath = path.join(ROOT, `supabase/migrations/${timestamp}_reseed_reference_data.sql`);
  writeFileSync(migrationPath, toSeedSql(out));

  console.log(`Exported ${npcReference.length} npcs, ${Object.keys(itemReference).length} items, ${Object.keys(containerReference).length} containers.`);
  console.log(`Wrote migration: ${path.basename(migrationPath)} — run "supabase db push" to apply it.`);
}

function sqlString(s) {
  return `'${s.replace(/'/g, "''")}'`;
}

function toSeedSql({ npcs, items, containers }) {
  const npcIds = npcs.map((n) => n.id);
  const itemIds = Object.keys(items);
  const containerIds = Object.keys(containers);

  const lines = [
    "-- Generated by scripts/export-reference-data.mjs. Re-run after",
    "-- npm run generate-monsters to refresh (safe to re-run: upserts on primary key).",
    "",
    // name/loot/is_pet columns come from the server-side-rolls migration
    // (20261107000000_server_side_rolls_competitive.sql) — the server rolls
    // every drop from `loot`, so it must always match the client's tables.
    "insert into public.npc_reference (id, name, unlock_cost, max_gp_per_kill, loot) values",
    npcs
      .map((n) => `  (${sqlString(n.id)}, ${sqlString(n.name)}, ${n.unlockCost}, ${n.maxGpPerKill}, ${sqlString(JSON.stringify(n.loot))}::jsonb)`)
      .join(",\n"),
    "on conflict (id) do update set name = excluded.name, unlock_cost = excluded.unlock_cost, max_gp_per_kill = excluded.max_gp_per_kill, loot = excluded.loot;",
    "",
    "insert into public.item_reference (id, name, value, tradeable, is_pet) values",
    Object.entries(items)
      .map(([id, it]) => `  (${sqlString(id)}, ${sqlString(it.name)}, ${it.value}, ${it.tradeable}, ${it.isPet})`)
      .join(",\n"),
    "on conflict (id) do update set name = excluded.name, value = excluded.value, tradeable = excluded.tradeable, is_pet = excluded.is_pet;",
    "",
    "insert into public.container_reference (item_id, name, max_gp_per_open, loot) values",
    Object.entries(containers)
      .map(([id, c]) => `  (${sqlString(id)}, ${sqlString(c.name)}, ${c.maxGpPerOpen}, ${sqlString(JSON.stringify(c.loot))}::jsonb)`)
      .join(",\n"),
    "on conflict (item_id) do update set name = excluded.name, max_gp_per_open = excluded.max_gp_per_open, loot = excluded.loot;",
    "",
    // Anything no longer in the generated set (e.g. a monster later removed
    // as low-value/miscategorized) needs to actually go away, not just stop
    // getting updated — a stale npc_reference row would make prestige's
    // "every monster unlocked" check permanently impossible to satisfy,
    // since it'd count something the client no longer offers to unlock.
    // npc_reference/container_reference have no incoming foreign keys, safe
    // to delete outright. item_reference does (user_items.item_id) — only
    // ever prune rows nobody actually holds, or the delete would fail (or
    // worse, take the item away from whoever's holding it).
    `delete from public.npc_reference where id not in (${npcIds.map(sqlString).join(", ")});`,
    `delete from public.item_reference where id not in (${itemIds.map(sqlString).join(", ")}) and id not in (select item_id from public.user_items);`,
    `delete from public.container_reference where item_id not in (${containerIds.map(sqlString).join(", ")});`,
    "",
  ];
  return lines.join("\n");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
