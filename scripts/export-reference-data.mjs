#!/usr/bin/env node
/**
 * Exports npc/item reference data used to seed Postgres validation tables
 * (see supabase/migrations). Transpiles src/data/npcData.ts with esbuild
 * and loads it directly, so this is always in sync with the real app data
 * rather than a second hand-maintained copy.
 *
 * Output: supabase/reference-data.json
 */
import { build } from "esbuild";
import { writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

function maxCoinsPerRoll(entries) {
  const coinEntries = entries.filter((e) => e.itemId === "coins");
  return coinEntries.reduce((sum, e) => sum + e.maxQuantity, 0);
}

async function main() {
  const outfile = path.join(mkdtempSync(path.join(tmpdir(), "npcdata-")), "npcData.cjs");
  await build({
    entryPoints: [path.join(ROOT, "src/data/npcData.ts")],
    bundle: true,
    platform: "node",
    format: "cjs",
    outfile,
  });
  const { npcs, items, containers } = await import(`file://${outfile}`);

  const npcReference = npcs.map((npc) => {
    // Generous ceiling: guaranteed coins + best possible single main-table coin
    // hit + every tertiary coin entry landing at once, times the roll count,
    // doubled for safety margin. Not exact game math — just a sanity bound.
    const alwaysCoins = maxCoinsPerRoll(npc.always);
    const mainCoins = Math.max(0, ...npc.mainTable.filter((e) => e.itemId === "coins").map((e) => e.maxQuantity), 0);
    const tertiaryCoins = maxCoinsPerRoll(npc.tertiary);
    const rolls = npc.mainRolls ?? 1;
    const ceiling = (alwaysCoins + mainCoins * rolls + tertiaryCoins) * 2 + 1000;
    return { id: npc.id, unlockCost: npc.unlockCost, maxGpPerKill: ceiling };
  });

  const itemReference = Object.fromEntries(
    Object.values(items).map((it) => [it.id, { value: it.value, tradeable: it.tradeable }]),
  );

  const containerReference = Object.fromEntries(
    Object.values(containers).map((c) => {
      const ceiling = (maxCoinsPerRoll(c.always) + maxCoinsPerRoll(c.mainTable) * (c.mainRolls ?? 1) + maxCoinsPerRoll(c.tertiary)) * 2 + 1000;
      return [c.itemId, { maxGpPerOpen: ceiling }];
    }),
  );

  const out = { npcs: npcReference, items: itemReference, containers: containerReference };
  writeFileSync(path.join(ROOT, "supabase/reference-data.json"), JSON.stringify(out, null, 2));

  writeFileSync(path.join(ROOT, "supabase/migrations/0003_seed_reference.sql"), toSeedSql(out));

  console.log(`Exported ${npcReference.length} npcs, ${Object.keys(itemReference).length} items, ${Object.keys(containerReference).length} containers.`);
}

function sqlString(s) {
  return `'${s.replace(/'/g, "''")}'`;
}

function toSeedSql({ npcs, items, containers }) {
  const lines = [
    "-- Generated by scripts/export-reference-data.mjs. Re-run after",
    "-- npm run generate-monsters to refresh (safe to re-run: upserts on primary key).",
    "",
    "insert into public.npc_reference (id, unlock_cost, max_gp_per_kill) values",
    npcs.map((n) => `  (${sqlString(n.id)}, ${n.unlockCost}, ${n.maxGpPerKill})`).join(",\n"),
    "on conflict (id) do update set unlock_cost = excluded.unlock_cost, max_gp_per_kill = excluded.max_gp_per_kill;",
    "",
    "insert into public.item_reference (id, value, tradeable) values",
    Object.entries(items)
      .map(([id, it]) => `  (${sqlString(id)}, ${it.value}, ${it.tradeable})`)
      .join(",\n"),
    "on conflict (id) do update set value = excluded.value, tradeable = excluded.tradeable;",
    "",
    "insert into public.container_reference (item_id, max_gp_per_open) values",
    Object.entries(containers)
      .map(([id, c]) => `  (${sqlString(id)}, ${c.maxGpPerOpen})`)
      .join(",\n"),
    "on conflict (item_id) do update set max_gp_per_open = excluded.max_gp_per_open;",
    "",
  ];
  return lines.join("\n");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
